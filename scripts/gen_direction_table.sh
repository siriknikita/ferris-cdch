#!/bin/sh
# Regenerate crates/cdch-core/src/directions_v8.rs from oracle/direction_table_v8.json.
# The JSON itself is produced by `node oracle/direction_table.js`.
set -eu
cd "$(dirname "$0")/.."
{
  echo "// @generated by scripts/gen_direction_table.sh from oracle/direction_table_v8.json — do not edit."
  jq -r '"// Source: Node \(.node), V8 \(.v8), \(.platform)-\(.arch)."' oracle/direction_table_v8.json
  echo "//"
  echo "// Bit patterns of Math.cos/Math.sin evaluated on radians = (angle - 90) * (Math.PI / 180),"
  echo "// exactly as written in ip-1.js, for integer angles 0..=359."
  echo "/// IEEE-754 bit patterns of \`Math.cos(radians)\` per integer degree."
  echo "pub(crate) const COS_BITS: [u64; 360] = ["
  jq -r '.rows[] | "    0x\(.cos),"' oracle/direction_table_v8.json
  echo "];"
  echo "/// IEEE-754 bit patterns of \`Math.sin(radians)\` per integer degree."
  echo "pub(crate) const SIN_BITS: [u64; 360] = ["
  jq -r '.rows[] | "    0x\(.sin),"' oracle/direction_table_v8.json
  echo "];"
  echo "/// IEEE-754 bit patterns of the \`radians\` argument per integer degree."
  echo "pub(crate) const RADIANS_BITS: [u64; 360] = ["
  jq -r '.rows[] | "    0x\(.radians),"' oracle/direction_table_v8.json
  echo "];"
} > crates/cdch-core/src/directions_v8.rs
